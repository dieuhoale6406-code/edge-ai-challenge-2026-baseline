"""Convert trained models into the C arrays that the firmware compiles in.

Usage:
    python tools/tflite_to_cc.py --det student_detector_int8.tflite \
        --text textcnn_int8.tflite --vocab intent_vocab.json --out main/models

Writes det_model.cc/.h, textcnn_model.cc/.h and vocab.cc/.h. Array names match
main/model_config.h, so the firmware builds without other changes.
"""
import argparse
import json
from pathlib import Path


def write_array(tflite: Path, name: str, out_dir: Path) -> int:
    data = tflite.read_bytes()
    if data[4:8] != b"TFL3":
        raise SystemExit(f"{tflite} is not a .tflite file (missing TFL3 marker)")
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    (out_dir / f"{name}.h").write_text(
        f"#pragma once\nextern const unsigned char {name}[];\nextern const unsigned int {name}_len;\n",
        encoding="utf-8", newline="\n")
    (out_dir / f"{name}.cc").write_text(
        f'// Generated by tools/tflite_to_cc.py from {tflite.name}. Do not edit.\n'
        f'#include "{name}.h"\n'
        f"alignas(16) const unsigned char {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"
        f"const unsigned int {name}_len = {len(data)};\n",
        encoding="utf-8", newline="\n")
    return len(data)


def write_vocab(vocab_json: Path, out_dir: Path) -> tuple[int, int]:
    data = json.loads(vocab_json.read_text(encoding="utf-8"))
    vocab = data["vocab"]
    ids = sorted(vocab.values())
    if ids != list(range(len(ids))) or vocab.get("<pad>") != 0 or vocab.get("<unk>") != 1:
        raise SystemExit("vocab must map <pad>=0, <unk>=1 and use contiguous ids")
    words = sorted((w for w in vocab if vocab[w] >= 2), key=vocab.get)   # words[k] has id k + 2
    for w in words:
        if not w.isascii() or " " in w or '"' in w or "\\" in w:
            raise SystemExit(f"unsupported vocab word: {w!r}")
    (out_dir / "vocab.h").write_text(
        "#pragma once\nextern const char *const vocab[];\nextern const int vocab_len;\n",
        encoding="utf-8", newline="\n")
    body = "".join(f'  "{w}",\n' for w in words)
    (out_dir / "vocab.cc").write_text(
        f"// Generated by tools/tflite_to_cc.py from {vocab_json.name}. vocab[k] has token id k + 2.\n"
        '#include "vocab.h"\nconst char *const vocab[] = {\n' + body + "};\n"
        f"const int vocab_len = {len(words)};\n",
        encoding="utf-8", newline="\n")
    return len(words), int(data.get("sequence_length", 0))


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--det", type=Path, required=True)
    p.add_argument("--text", type=Path, required=True)
    p.add_argument("--vocab", type=Path, required=True)
    p.add_argument("--out", type=Path, default=Path("main/models"))
    a = p.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    print(f"det_model: {write_array(a.det, 'det_model', a.out)} bytes")
    print(f"textcnn_model: {write_array(a.text, 'textcnn_model', a.out)} bytes")
    n, seq = write_vocab(a.vocab, a.out)
    print(f"vocab: {n} words, sequence_length={seq} (must match SEQ_LEN in main/logic.h)")


if __name__ == "__main__":
    main()
